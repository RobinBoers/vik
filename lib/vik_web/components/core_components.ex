  ## JS Commands

  @doc """
  Same as `Phoenix.LiveView.JS.show/2`.

  Left here for backwards compatibility.
  """
  def show(js \\ %JS{}, selector) do
    JS.show(js, to: selector)
  end

  @doc """
  Same as `Phoenix.LiveView.JS.hide/2`.

  Left here for backwards compatibility.
  """
  def hide(js \\ %JS{}, selector) do
